/** Research-only R2 teacher pilot. Historical a13 campaigns retain their original identities. */
import { createHash } from "node:crypto";
import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

import type { A19AuditProfile } from "../a19_decision_audit";
import { hashSimulationParts, makeRng } from "../army";
import { fingerprintV09 } from "./protocol";
import { V09_A19_OBSERVATION_SHA256 } from "./a19_observation";

export const V09_A19_PILOT_SCHEMA = "hoc.ai.v0_9_a19_pilot.v2" as const;
export const V09_A19_PILOT_STAGES = {
    smoke: 3,
    aa: 12,
    teacher_screen: 192,
    teacher_confirmation: 1500,
    corpus_train: 510,
    corpus_validation: 96,
} as const;
export type V09A19PilotStage = keyof typeof V09_A19_PILOT_STAGES;

export const V09_A19_WIDE_TEACHER = Object.freeze({
    SEARCH_HORIZON: "64",
    SEARCH_ROLLOUTS: "4",
    SEARCH_A19_COMPLEMENTARY_R2: "0",
    SEARCH_SHORTLIST: "12",
    SEARCH_MAX_MOVES: "8",
    SEARCH_MAX_MELEE: "16",
    SEARCH_MAX_SHOTS: "16",
    SEARCH_MAX_THROWS: "8",
    SEARCH_MAX_MOVE_SHOTS: "2",
    SEARCH_MOVE_SHOT_VERSIONS: "v0.8",
    SEARCH_A19_CERTIFIED_SELECTION_BOUNDS: "0",
    SEARCH_A19_CERTIFIED_TIGHT_BOUNDS: "0",
});

/** Spend the comparison budget on repeated estimates of the production catalog, rather than more actions. */
export const V09_A19_PRECISE_TEACHER = Object.freeze({
    SEARCH_HORIZON: "64",
    SEARCH_ROLLOUTS: "8",
    SEARCH_A19_COMPLEMENTARY_R2: "0",
    SEARCH_SHORTLIST: "6",
    SEARCH_A19_CERTIFIED_SELECTION_BOUNDS: "0",
    SEARCH_A19_CERTIFIED_TIGHT_BOUNDS: "0",
});
export const V09_A19_TEACHERS = Object.freeze({
    "wide-r4": V09_A19_WIDE_TEACHER,
    "precise-r8": V09_A19_PRECISE_TEACHER,
});
export type V09A19TeacherPreset = keyof typeof V09_A19_TEACHERS;

export interface IV09PilotSource {
    readonly files: Record<string, string>;
    readonly sha256: string;
}

/** Only source inputs enter this identity; Python's generated bytecode cannot invalidate a run. */
export function readV09PilotSource(root: string): IV09PilotSource {
    const files: Record<string, string> = {};
    const walk = (folder: string): void => {
        for (const entry of readdirSync(join(root, folder), { withFileTypes: true }).sort((a, b) =>
            a.name.localeCompare(b.name),
        )) {
            if (entry.name === "__pycache__") continue;
            const name = join(folder, entry.name);
            if (entry.isDirectory()) walk(name);
            else if (entry.isFile() && !name.endsWith(".pyc")) {
                files[name] = createHash("sha256")
                    .update(readFileSync(join(root, name)))
                    .digest("hex");
            } else if (entry.isSymbolicLink()) throw new Error(`Pilot source contains a symbolic link: ${name}`);
        }
    };
    walk("src");
    for (const name of ["package.json", "bun.lock"])
        files[name] = createHash("sha256")
            .update(readFileSync(join(root, name)))
            .digest("hex");
    return { files, sha256: fingerprintV09(files) };
}

export interface IV09A19PilotManifest {
    readonly schema: typeof V09_A19_PILOT_SCHEMA;
    readonly promoted: false;
    readonly source: IV09PilotSource;
    readonly profile: A19AuditProfile;
    readonly baseline: Record<string, string>;
    readonly teacher: Record<string, string>;
    readonly teacherPreset: V09A19TeacherPreset;
    readonly seed: number;
    readonly stages: Record<V09A19PilotStage, readonly number[]>;
    readonly sourceCommit: string;
    readonly runtime: string;
    readonly observationSha256: string;
    readonly protectedV08Roots: readonly string[];
    readonly manifestSha256: string;
}

export function buildV09A19PilotManifest(input: {
    source: IV09PilotSource;
    profile: A19AuditProfile;
    seed: number;
    sourceCommit: string;
    runtime: string;
    protectedV08Roots: readonly string[];
    teacherPreset?: V09A19TeacherPreset;
}): IV09A19PilotManifest {
    if (!Number.isSafeInteger(input.seed) || input.seed < 0 || input.seed > 0xffffffff)
        throw new Error("Pilot seed must be uint32");
    if (!/^[0-9a-f]{40,64}$/.test(input.sourceCommit)) throw new Error("Pilot requires its base source commit");
    if (fingerprintV09(input.source.files) !== input.source.sha256) throw new Error("Invalid pilot source identity");
    const baseline = Object.fromEntries(
        Object.entries(input.profile.environment).filter((entry): entry is [string, string] => entry[1] !== undefined),
    );
    const profile = {
        ...input.profile,
        environment: baseline,
        overrides: Object.fromEntries(
            Object.entries(input.profile.overrides).filter(([, value]) => value !== undefined),
        ),
    };
    if (
        baseline.SEARCH_HORIZON !== "64" ||
        baseline.SEARCH_ROLLOUTS !== "2" ||
        baseline.SEARCH_SHORTLIST !== "6" ||
        baseline.SEARCH_A19_COMPLEMENTARY_R2 !== "1"
    )
        throw new Error("Pilot baseline must be the current complementary R2 A19 profile");
    const teacherPreset = input.teacherPreset ?? "wide-r4";
    if (!Object.hasOwn(V09_A19_TEACHERS, teacherPreset)) throw new Error("Unknown registered teacher preset");
    const seen = new Set<number>();
    const stages = {} as Record<V09A19PilotStage, number[]>;
    for (const [stage, count] of Object.entries(V09_A19_PILOT_STAGES)) {
        const seeds: number[] = [];
        for (let ordinal = 0; seeds.length < count; ordinal++) {
            const seed = hashSimulationParts(V09_A19_PILOT_SCHEMA, input.seed, stage, ordinal);
            // Each draft board consumes three adjacent seed channels. Reserve all of them across phases.
            if (seed <= 0xffffffff - 5 && [0, 1, 2].every((offset) => !seen.has(seed + offset))) {
                for (const offset of [0, 1, 2]) seen.add(seed + offset);
                seeds.push(seed);
            }
        }
        stages[stage as V09A19PilotStage] = seeds;
    }
    const unsigned = {
        schema: V09_A19_PILOT_SCHEMA,
        promoted: false as const,
        source: input.source,
        profile,
        seed: input.seed,
        sourceCommit: input.sourceCommit,
        runtime: input.runtime,
        observationSha256: V09_A19_OBSERVATION_SHA256,
        protectedV08Roots: input.protectedV08Roots,
        baseline,
        teacherPreset,
        teacher: { ...baseline, ...V09_A19_TEACHERS[teacherPreset] },
        stages,
    };
    return { ...unsigned, manifestSha256: fingerprintV09(unsigned) };
}

export function validateV09A19PilotManifest(manifest: IV09A19PilotManifest): void {
    const { manifestSha256, ...unsigned } = manifest;
    if (
        manifest.schema !== V09_A19_PILOT_SCHEMA ||
        manifest.promoted !== false ||
        fingerprintV09(unsigned) !== manifestSha256
    )
        throw new Error("Pilot manifest identity mismatch");
    const rebuilt = buildV09A19PilotManifest(manifest);
    if (rebuilt.manifestSha256 !== manifestSha256)
        throw new Error("Pilot seed schedule or teacher configuration changed");
}

/** Stratified whole-board bootstrap: all four draft-seat/battle-seat cases stay in one confidence unit. */
export function v09PilotBoardStatistics(scores: readonly number[], seed: number, samples = 10_000) {
    if (!scores.length || scores.length % 3 || scores.some((x) => !Number.isFinite(x) || x < 0 || x > 1))
        throw new Error("Pilot statistics require complete three-map board scores");
    if (!Number.isSafeInteger(samples) || samples < 1000) throw new Error("Insufficient bootstrap samples");
    const mean = scores.reduce((sum, score) => sum + score, 0) / scores.length;
    if (scores.length < 6)
        return { boards: scores.length, games: scores.length * 4, score: mean, lower95: null, upper95: null };
    const groups = [0, 1, 2].map((map) => scores.filter((_, index) => index % 3 === map));
    const random = makeRng(seed);
    const draws = Array.from({ length: samples }, () => {
        let sum = 0;
        for (const group of groups)
            for (let index = 0; index < group.length; index++) sum += group[Math.floor(random() * group.length)];
        return sum / scores.length;
    }).sort((a, b) => a - b);
    return {
        boards: scores.length,
        games: scores.length * 4,
        score: mean,
        lower95: draws[Math.floor(samples * 0.025)],
        upper95: draws[Math.floor(samples * 0.975)],
    };
}
