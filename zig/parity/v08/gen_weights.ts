/**
 * Writes zig/src/v08/weights.zig: StrategyV0_8's learned weight vector (`this.w` after applyMeleeDims, the default
 * environment), each value as its exact IEEE-754 bit pattern, named by V05_WEIGHT_KEYS.
 *
 *   bun zig/parity/v08/gen_weights.ts
 */

import { writeFileSync } from "node:fs";
import { getAIStrategy } from "../../../src/ai";
import { V05_WEIGHT_KEYS } from "../../../src/ai/versions/v0_5_weights";
import { v07BakedWaitWeights, WAIT_FEATURE_NAMES } from "../../../src/ai/versions/wait_scorer";
import { V08_A13_VALUE_LEAF } from "../../../src/ai/versions/v0_8_a13_profile";
import { VALUE_FEATURE_NAMES_V2 } from "../../../src/simulation/value_features";

const strategy = getAIStrategy("v0.8s") as unknown as { w: number[]; applyMeleeDims(): void };
strategy.applyMeleeDims();
const w = strategy.w;
const view = new DataView(new ArrayBuffer(8));
const bitsOf = (value: number): string => {
    view.setFloat64(0, value);
    return view.getBigUint64(0).toString(16).padStart(16, "0");
};
const rows = w.map(
    (value, i) => `    @bitCast(@as(u64, 0x${bitsOf(value)})), // ${i} ${V05_WEIGHT_KEYS[i] ?? "?"} = ${value}`,
);
const wait = v07BakedWaitWeights();
if (!wait) throw new Error("no baked wait weights in this environment");
const text = [
    "//! Generated by zig/parity/v08/gen_weights.ts: StrategyV0_8's learned weights (`this.w` after applyMeleeDims,",
    "//! default environment) as exact bit patterns. Do not edit; regenerate.",
    "",
    `pub const W = [${w.length}]f64{`,
    ...rows,
    "};",
    "",
    "/// v0.7's baked act-vs-wait scorer (wait_scorer.ts v07BakedWaitWeights: bias and one weight per WAIT_FEATURE_NAMES).",
    `pub const WAIT_B: f64 = @bitCast(@as(u64, 0x${bitsOf(wait.b)})); // ${wait.b}`,
    `pub const WAIT_W = [${wait.w.length}]f64{`,
    ...wait.w.map(
        (value, i) => `    @bitCast(@as(u64, 0x${bitsOf(value)})), // ${i} ${WAIT_FEATURE_NAMES[i]} = ${value}`,
    ),
    "};",
    "",
    "/// The production rollout leaf (V08_A13_VALUE_LEAF = V07_VALUE_WEIGHTS_V2): bias and one weight per V2 feature.",
    `pub const LEAF_V2_B: f64 = @bitCast(@as(u64, 0x${bitsOf(V08_A13_VALUE_LEAF.b)})); // ${V08_A13_VALUE_LEAF.b}`,
    `pub const LEAF_V2_W = [${V08_A13_VALUE_LEAF.w.length}]f64{`,
    ...V08_A13_VALUE_LEAF.w.map(
        (value: number, i: number) =>
            `    @bitCast(@as(u64, 0x${bitsOf(value)})), // ${i} ${VALUE_FEATURE_NAMES_V2[i]} = ${value}`,
    ),
    "};",
    "",
].join("\n");
writeFileSync("zig/src/v08/weights.zig", text);
console.log(`wrote ${w.length} weights`);
