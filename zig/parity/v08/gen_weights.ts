/**
 * Writes zig/src/v08/weights.zig: StrategyV0_8's learned weight vector (`this.w` after applyMeleeDims, the default
 * environment), each value as its exact IEEE-754 bit pattern, named by V05_WEIGHT_KEYS.
 *
 *   bun zig/parity/v08/gen_weights.ts
 */

import { writeFileSync } from "node:fs";
import { getAIStrategy } from "../../../src/ai";
import { V05_WEIGHT_KEYS } from "../../../src/ai/versions/v0_5_weights";

const strategy = getAIStrategy("v0.8s") as unknown as { w: number[]; applyMeleeDims(): void };
strategy.applyMeleeDims();
const w = strategy.w;
const view = new DataView(new ArrayBuffer(8));
const rows = w.map((value, i) => {
    view.setFloat64(0, value);
    const bits = view.getBigUint64(0).toString(16).padStart(16, "0");
    return `    @bitCast(@as(u64, 0x${bits})), // ${i} ${V05_WEIGHT_KEYS[i] ?? "?"} = ${value}`;
});
const text = [
    "//! Generated by zig/parity/v08/gen_weights.ts: StrategyV0_8's learned weights (`this.w` after applyMeleeDims,",
    "//! default environment) as exact bit patterns. Do not edit; regenerate.",
    "",
    `pub const W = [${w.length}]f64{`,
    ...rows,
    "};",
    "",
].join("\n");
writeFileSync("zig/src/v08/weights.zig", text);
console.log(`wrote ${w.length} weights`);
